# 清單沒有的段落
OTHER = ['L02:5', 'L04:3', 'L04:7', 'L06:6', 'L06:7', 'L08:5', 'L35:5', 'L35:6']

pl5 = json.load(open('data/playlist-n5.json', encoding='utf-8'))['items']
pl4 = json.load(open('data/playlist-n4.json', encoding='utf-8'))['items']

# 題目名對調：清單第 3、4 題的內容次序照使用者指定，題目名一齊對調
TITLE_SWAP = {('n5', 3): 4, ('n5', 4): 3}

items = []
for book, pl in (('n5', pl5), ('n4', pl4)):
    titles = {x['no']: x['title'] for x in pl}
    for it in pl:
        no = it['no']
        title = titles[TITLE_SWAP[(book, no)]] if (book, no) in TITLE_SWAP else it['title']
        items.append({'pl': book, 'no': no, 't': title,
                      'keys': ASSIGN.get((book, no), [])})
items.append({'pl': 'other', 'no': 0, 't': '其他（清單沒有）', 'keys': OTHER})

# ---- 驗證 ----
have = {}
for f in glob.glob('data/lesson-L*.json'):
    d = json.load(open(f, encoding='utf-8'))
    for i, g in enumerate(d.get('grammar', [])):
        have['%s:%d' % (d['id'], i)] = g['h']

seen, dup = {}, []
for it in items:
    for k in it['keys']:
        if k in seen: dup.append((k, seen[k], it['t']))
        seen[k] = it['t']
missing = [k for k in have if k not in seen]
bogus = [k for k in seen if k not in have]

print('題目', len(items), '有內容', sum(1 for i in items if i['keys']),
      '段落', len(have), '已排', len(seen))
for label, lst in (('重複', dup), ('未排', missing), ('不存在', bogus)):
    if lst:
        print(label, len(lst))
        for x in lst[:40]:
            k = x if isinstance(x, str) else x[0]
            print('   ', x, have.get(k, ''))
if dup or missing or bogus:
    sys.exit(1)

