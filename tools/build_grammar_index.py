# ---- 驗證：全部 295 段都要出現且只出現一次 ----
have = {}
for f in glob.glob('data/lesson-L*.json'):
    d = json.load(open(f, encoding='utf-8'))
    for i, g in enumerate(d.get('grammar', [])):
        have['%s:%d' % (d['id'], i)] = g['h']

seen, dup = {}, []
for t, keys in ORDER:
    for k in keys:
        if k in seen: dup.append((k, seen[k], t))
        seen[k] = t
missing = [k for k in have if k not in seen]
bogus = [k for k in seen if k not in have]

groups = [{'t': t, 'keys': keys} for t, keys in ORDER]

print('段落', len(have), '已排', len(seen), '組', len(groups))
for label, lst in (('重複', dup), ('未排', missing), ('不存在', bogus)):
    if lst:
        print(label, len(lst))
        for item in lst[:40]:
            print('   ', item, have.get(item if isinstance(item, str) else item[0], ''))
if dup or missing or bogus:
    sys.exit(1)

