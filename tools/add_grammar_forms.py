def indent_of(text):
    """沿用每個檔案原本的縮排（各課檔案有 1 格、2 格兩種寫法）。"""
    for line in text.splitlines()[1:]:
        m = re.match(r'^(\s+)"', line)
        if m:
            return len(m.group(1))
    return 2


def main():
    missing, added = [], 0
    for lid, mp in MAP.items():
        path = os.path.join(ROOT, f"data/lesson-{lid}.json")
        raw = open(path, encoding="utf-8").read()
        d = json.loads(raw)
        names = {g["h"] for g in d.get("grammar", [])}
        for h in mp:
            if h not in names:
                missing.append((lid, h))
        for g in d.get("grammar", []):
            if g["h"] in mp:
                old = g.get("form")
                new = mp[g["h"]]
                if old != new:
                    added += 1
                # 保持 h、form 在最前，其餘欄位照原次序
                items = [("h", g["h"]), ("form", new)] + \
                        [(k, v) for k, v in g.items() if k not in ("h", "form")]
                g.clear()
                g.update(items)
        open(path, "w", encoding="utf-8").write(
            json.dumps(d, ensure_ascii=False, indent=indent_of(raw)) + "\n")
    print("寫入段落：", added)
    if missing:
        print("找不到的標題：")
        for m in missing:
            print("  ", m)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
